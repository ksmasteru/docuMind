package com.docuMind.backend.model;

import java.time.Instant;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;

import com.docuMind.backend.model.enums.FixType;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;

// contains meta data for the image, point to image data.
@Entity
@Table(name = "images_metadata", indexes = {
    @Index(name = "idx_images_user", columnList = "uploadedBy"),
    @Index(name = "idx_images_report", columnList = "reportId")
})
public class ImageEntity {

    // set in the constructor, not generated by Hibernate:
    // ImageData reuses this same id, so it must exist before saving
    @Id
    private String id;

    @Column(nullable = false)
    private long size;

    @Column(nullable = false)
    private String name;

    @Column(nullable = false)
    private String contentType;

    // email..
    @Column(nullable = false)
    private String uploadedBy;

    // what report. null until the submission that uses the image is saved
    @Column
    private String reportId;

    @Column
    private String equipementId; //photo of which equipement

    @Enumerated(EnumType.STRING)
    @Column
    private FixType fix; // here was it maintenace fault ?

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private Instant createdAt;

    // No byte[] data here — that lives in ImageData.

    public ImageEntity() {}

    public ImageEntity(String name, String contentType, long size,
                       String uploadedBy) {
        this.id = UUID.randomUUID().toString();
        this.name = name;
        this.contentType = contentType;
        this.size = size;
        this.uploadedBy = uploadedBy;
    }

    public String getId()                   { return id; }
    public void setId(String id)            { this.id = id; }
    public long getSize()                   { return size; }
    public void setSize(long s)             { this.size = s; }
    public String getName()                 { return name; }
    public void setName(String n)           { this.name = n; }
    public String getContentType()          { return contentType; }
    public void setContentType(String ct)   { this.contentType = ct; }
    public String getUploadedBy()           { return uploadedBy; }
    public void setUploadedBy(String u)     { this.uploadedBy = u; }
    public String getReportId()             { return reportId; }
    public void setReportId(String r)       { this.reportId = r; }
    public String getEquipementId()         { return equipementId; }
    public void setEquipementId(String e)   { this.equipementId = e; }
    public FixType getFix()                 { return fix; }
    public void setFix(FixType fix)         { this.fix = fix; }
    public Instant getCreatedAt()           { return createdAt; }
}
