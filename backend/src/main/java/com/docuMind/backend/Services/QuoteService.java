package com.docuMind.backend.services;

import java.time.Instant;
import java.util.List;

import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.stereotype.Service;

import com.docuMind.backend.exception.InterventionNotFoundException;
import com.docuMind.backend.exception.InvalidQuoteException;
import com.docuMind.backend.exception.QuoteNotFoundException;
import com.docuMind.backend.model.Intervention;
import com.docuMind.backend.model.Quote;
import com.docuMind.backend.model.QuoteDetails;
import com.docuMind.backend.model.QuoteLine;
import com.docuMind.backend.model.QuoteLinesDto;
import com.docuMind.backend.model.enums.InterventionStatus;
import com.docuMind.backend.model.enums.QuoteStatus;
import com.docuMind.backend.model.enums.StepStatus;
import com.docuMind.backend.model.enums.UserRole;
import com.docuMind.backend.model.enums.WorkshopStep;
import com.docuMind.backend.repository.InterventionRepository;
import com.docuMind.backend.repository.QuoteRepository;

import jakarta.transaction.Transactional;

// The devis of a workshop intervention (Quote). The Chef de projet opens a draft at step 10 and
// fills in its parts (QuoteLine); every workshop role reads it. Sending it to Sales and the
// client's answer come next.
@Service
public class QuoteService {
    private final QuoteRepository quoteRepository;
    private final InterventionRepository interventionRepository;

    public QuoteService(QuoteRepository quoteRepository, InterventionRepository interventionRepository)
    {
        this.quoteRepository = quoteRepository;
        this.interventionRepository = interventionRepository;
    }

    // "Générer le devis": the Chef de projet who took step 10 opens the intervention's draft.
    // If a draft is already open it is returned as it is, so pressing the button twice doesn't make
    // two; otherwise a new version starts (1, then 2, 3… after a revision).
    @Transactional
    @PreAuthorize("hasRole('PROJECT_LEAD')")
    public QuoteDetails createDraft(String interventionId, Authentication caller)
    {
        Intervention intervention = findIntervention(interventionId);
        if (!canQuote(intervention, caller.getName()))
            throw new InvalidQuoteException("a quote is generated by the Chef de projet who took step "
                    + WorkshopStep.VALIDER_BESOINS_DEVIS.number() + " (" + WorkshopStep.VALIDER_BESOINS_DEVIS.getLabel() + ")");

        Quote quote = quoteRepository.findFirstByInterventionIdAndStatus(interventionId, QuoteStatus.DRAFT)
            .orElseGet(() -> {
                int version = quoteRepository.findFirstByInterventionIdOrderByVersionDesc(interventionId)
                    .map(latest -> latest.getVersion() + 1).orElse(1);
                // saveAndFlush: the insert runs now, so createdAt / updatedAt come back filled
                return quoteRepository.saveAndFlush(new Quote(interventionId, version, caller.getName()));
            });
        return QuoteDetails.from(quote, intervention, true);
    }

    // "Valider" on the devis page: the parts replace the ones saved before. Only the Chef de projet
    // who took step 10, on a draft. Returns the saved quote
    @Transactional
    @PreAuthorize("hasRole('PROJECT_LEAD')")
    public QuoteDetails saveLines(String quoteId, QuoteLinesDto request, Authentication caller)
    {
        Quote quote = quoteRepository.findById(quoteId)
            .orElseThrow(() -> new QuoteNotFoundException("no quote with id " + quoteId));
        Intervention intervention = findIntervention(quote.getInterventionId());
        if (!canEdit(quote, intervention, caller.getName()))
            throw new InvalidQuoteException("quote " + quoteId + " (" + quote.getStatus() + ") can only be changed as a draft, by the Chef de projet who took step "
                    + WorkshopStep.VALIDER_BESOINS_DEVIS.number());

        quote.setLines(request.lines().stream()
            .map(line -> new QuoteLine(line.designation().strip(), line.quantity(), line.unitPrice()))
            .toList());
        // TVA applies unless the box was unticked
        quote.setVatApplicable(request.vatApplicable() == null || request.vatApplicable());
        quote.setValidatedAt(Instant.now());
        Quote saved = quoteRepository.saveAndFlush(quote);

        // the intervention's devis is now this one (null until the first "Valider")
        intervention.setQuoteId(saved.getId());
        interventionRepository.save(intervention);
        return QuoteDetails.from(saved, intervention, true);
    }

    // one quote. Same readers as the intervention: every workshop role, and admins
    @Transactional // the lines are loaded lazily
    public QuoteDetails getQuote(String quoteId, Authentication caller)
    {
        checkReader(caller);
        Quote quote = quoteRepository.findById(quoteId)
            .orElseThrow(() -> new QuoteNotFoundException("no quote with id " + quoteId));
        Intervention intervention = findIntervention(quote.getInterventionId());
        return QuoteDetails.from(quote, intervention, canEdit(quote, intervention, caller.getName()));
    }

    // an intervention's quotes, the newest version first
    @Transactional // the lines are loaded lazily
    public List<QuoteDetails> getQuotesOf(String interventionId, Authentication caller)
    {
        checkReader(caller);
        Intervention intervention = findIntervention(interventionId);
        return quoteRepository.findByInterventionIdOrderByVersionDesc(interventionId).stream()
            .map(quote -> QuoteDetails.from(quote, intervention, canEdit(quote, intervention, caller.getName())))
            .toList();
    }

    // step 10 taken by this user (the intervention page's "Générer le devis", InterventionService.canQuote)
    public static boolean canQuote(Intervention intervention, String email)
    {
        return intervention.getStatus() == InterventionStatus.EN_COURS
            && intervention.getCurrentStep() == WorkshopStep.VALIDER_BESOINS_DEVIS
            && intervention.getStepStatus() == StepStatus.EN_COURS
            && email.equals(intervention.getStepAssignee());
    }

    // a draft, while its step 10 is held by this user (a PROJECT_LEAD: only that role takes step 10)
    private static boolean canEdit(Quote quote, Intervention intervention, String email)
    {
        return quote.getStatus() == QuoteStatus.DRAFT && canQuote(intervention, email);
    }

    private Intervention findIntervention(String interventionId)
    {
        return interventionRepository.findById(interventionId)
            .orElseThrow(() -> new InterventionNotFoundException("no intervention with id " + interventionId));
    }

    private static void checkReader(Authentication caller)
    {
        UserRole role = caller.getAuthorities().stream()
            .map(GrantedAuthority::getAuthority)
            .filter(authority -> authority.startsWith("ROLE_"))
            .map(authority -> UserRole.valueOf(authority.substring("ROLE_".length())))
            .findFirst()
            .orElseThrow(() -> new AccessDeniedException("no role in the token"));
        if (role != UserRole.ADMIN && WorkshopStep.forRole(role).isEmpty())
            throw new AccessDeniedException("only the workshop roles read the quotes");
    }
}
